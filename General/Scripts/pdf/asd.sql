SELECT
	RESTAURANT_NAME,
	COUNT_NO
FROM 
	RESTAURANT
JOIN 
	(SELECT
		RESTAURANT_NO,
	 	COUNT(LIKE_FL) AS "COUNT_NO"
	FROM
	 REVIEW 
	WHERE
		LIKE_FL = 'N'
	GROUP BY 
		RESTAURANT_NO
	ORDER BY 
		COUNT_NO DESC	) 
USING (RESTAURANT_NO);
	
